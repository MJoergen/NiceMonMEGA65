#!/usr/bin/env python3
# Generates src/video/font_pkg.vhd, the character ROM of the text display
# (see src/video/text.vhd), from niceemu's font, src/font.zig of nice_cpu's
# emulator, so that the board and niceemu show the same glyphs. That font
# is Spleen 16x32: its glyphs for the codes 0x20 to 0xFF, ISO 8859-1, and
# blocks and arrows at 0x80 to 0x99 (nice_cpu's DEVICES.md 1.8), of which
# the four diagonal arrows are drawn by nice_cpu's emulator/font/gen_font.py,
# not Spleen's. The codes below 0x20, 0x7F, and 0x9A to 0x9F are blank.
# Spleen is licensed under the BSD 2-Clause license, see LICENSE.spleen.
#
# Adapted from font/gen_font_pkg.py of MandelbrotMEGA65
# (https://github.com/MJoergen/MandelbrotMEGA65, commit a3fafd4), MIT
# License, which generates only the digits.
#
# Usage (from the top directory of the repository):
#   python3 font/gen_font_pkg.py nice_cpu/emulator/src/font.zig > src/video/font_pkg.vhd
# "make -C sim check-font" compares the result with src/video/font_pkg.vhd.

import re
import sys

WIDTH  = 16
HEIGHT = 32


def load_zig(filename: str) -> tuple[str, list[list[int]]]:
    """Returns the version of Spleen, and the rows of the 256 glyphs."""
    version = ''
    glyphs: list[list[int]] = []
    for line in open(filename, encoding='utf-8'):
        m = re.match(r'//! The font of the window: Spleen \d+x\d+ (\S+),', line)
        if m:
            version = m.group(1)
        m = re.match(r'\s*\.\{ (.*) \}, // 0x([0-9A-F]{2})$', line)
        if m:
            assert int(m.group(2), 16) == len(glyphs), 'Glyphs out of order'
            rows = [int(word, 16) for word in m.group(1).split(', ')]
            assert len(rows) == HEIGHT, 'Wrong glyph size'
            glyphs.append(rows)
    assert version, 'No version of Spleen'
    assert len(glyphs) == 256, 'Not 256 glyphs'
    return version, glyphs


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit('usage: gen_font_pkg.py nice_cpu/emulator/src/font.zig > src/video/font_pkg.vhd')
    version, glyphs = load_zig(sys.argv[1])

    print('-- This file is generated by font/gen_font_pkg.py from niceemu\'s font,')
    print('-- emulator/src/font.zig of nice_cpu. Do not edit.')
    print('--')
    print('-- The characters 0x20 to 0xFF (ISO 8859-1) of the Spleen 16x32 font, version')
    print('-- %s, from https://github.com/fcambus/spleen (spleen-16x32.bdf), and at' % version)
    print('-- 0x80 to 0x99 the blocks U+2580 to U+258F and the arrows U+2190 to U+2199,')
    print('-- of which U+2196 to U+2199 are not Spleen\'s:')
    print('--')
    for line in open(sys.argv[0].replace('gen_font_pkg.py', 'LICENSE.spleen')):
        print(('-- ' + line.rstrip()).rstrip())
    print('--')
    print('-- C_FONT holds %d rows of %d pixels for each of the 256 codes, the top' % (HEIGHT, WIDTH))
    print('-- row first. The row r of the character with the code c is at index')
    print('-- 32*c + r. The leftmost pixel is bit 15. The codes below 0x20, 0x7F, and')
    print('-- 0x9A to 0x9F are blank.')
    print('')
    print('library ieee;')
    print('   use ieee.std_logic_1164.all;')
    print('')
    print('package font_pkg is')
    print('')
    print('   type t_font is array (0 to %d) of std_logic_vector(%d downto 0);' % (256*HEIGHT-1, WIDTH-1))
    print('')
    print('   constant C_FONT : t_font := (')
    for c, rows in enumerate(glyphs):
        if not any(rows):
            continue
        print('      -- 0x%02X' % c)
        for r, value in enumerate(rows):
            if value == 0:
                continue
            picture = ''.join('#' if value >> (WIDTH-1-i) & 1 else '.' for i in range(WIDTH))
            print('      %4d => "%s",  -- %s' % (HEIGHT*c + r, format(value, '0%db' % WIDTH), picture))
    # The comment keeps "others" out of the last glyph's group, so that the
    # "=>" of each group line up, as vsg requires.
    print('      -- The rest is blank')
    print('      others => (others => \'0\'));')
    print('')
    print('end package font_pkg;')


if __name__ == '__main__':
    main()
