#!/usr/bin/env python3
# Generates src/video/font_pkg.vhd, the font of the text display (see
# src/video/text.vhd), from the Spleen 16x32 font. It has the glyphs of
# Spleen for the codes 0x20 to 0xFF, ISO 8859-1. The codes below 0x20, and
# those that Spleen has no glyph for (0x80 to 0x9F), are blank. Spleen is
# licensed under the BSD 2-Clause license, see LICENSE.spleen.
#
# Adapted from font/gen_font_pkg.py of MandelbrotMEGA65
# (https://github.com/MJoergen/MandelbrotMEGA65, commit a3fafd4), MIT
# License, which generates only the digits.
#
# The font file (spleen-16x32.bdf) is not in this repository. The current
# src/video/font_pkg.vhd is from version 2.2.0, the tag 2.2.0 of the Spleen
# repository, and this gives exactly the same file. Usage (from the top
# directory of the repository):
#   git clone --branch 2.2.0 https://github.com/fcambus/spleen
#   python3 font/gen_font_pkg.py spleen/spleen-16x32.bdf > src/video/font_pkg.vhd
# The version is in the header of the generated file.

import sys

WIDTH  = 16
HEIGHT = 32


def load_bdf(filename):
    """Returns the version, and a dictionary from code point to the rows of
    the glyph."""
    glyphs  = {}
    version = None
    code    = None
    rows    = None
    for line in open(filename):
        words = line.split()
        if not words:
            continue
        if words[0] == 'FONT_VERSION':
            version = words[1].strip('"')
        elif words[0] == 'FONTBOUNDINGBOX':
            assert words[1:3] == [str(WIDTH), str(HEIGHT)], 'Wrong font size'
        elif words[0] == 'ENCODING':
            code = int(words[1])
        elif words[0] == 'BBX':
            # All glyphs of Spleen fill the whole cell
            assert words[1:3] == [str(WIDTH), str(HEIGHT)], 'Wrong glyph size'
        elif words[0] == 'BITMAP':
            rows = []
        elif words[0] == 'ENDCHAR':
            glyphs[code] = rows
            rows = None
        elif rows is not None:
            rows.append(int(words[0], 16))
    return version, glyphs


def main():
    if len(sys.argv) != 2:
        sys.exit('usage: gen_font_pkg.py spleen-16x32.bdf > src/video/font_pkg.vhd')
    version, glyphs = load_bdf(sys.argv[1])

    print('-- This file is generated by font/gen_font_pkg.py. Do not edit.')
    print('--')
    print('-- The characters 0x20 to 0xFF (ISO 8859-1) of the Spleen 16x32 font, version')
    print('-- %s, from https://github.com/fcambus/spleen (spleen-16x32.bdf):' % version)
    print('--')
    for line in open(sys.argv[0].replace('gen_font_pkg.py', 'LICENSE.spleen')):
        print(('-- ' + line.rstrip()).rstrip())
    print('--')
    print('-- C_FONT holds %d rows of %d pixels for each of the 256 codes of ISO' % (HEIGHT, WIDTH))
    print('-- 8859-1, the top row first. The row r of the character with the code c is')
    print('-- at index 32*c + r. The leftmost pixel is bit 15. The codes below 0x20, and')
    print('-- those that Spleen has no glyph for, are blank.')
    print('')
    print('library ieee;')
    print('   use ieee.std_logic_1164.all;')
    print('')
    print('package font_pkg is')
    print('')
    print('   type t_font is array (0 to %d) of std_logic_vector(%d downto 0);' % (256*HEIGHT-1, WIDTH-1))
    print('')
    print('   constant C_FONT : t_font := (')
    for c in range(256):
        if c not in glyphs or c < 0x20:
            continue
        rows = glyphs[c]
        if not any(rows):
            continue
        print('      -- 0x%02X' % c)
        for r, value in enumerate(rows):
            if value == 0:
                continue
            picture = ''.join('#' if value >> (WIDTH-1-i) & 1 else '.' for i in range(WIDTH))
            print('      %4d => "%s",  -- %s' % (HEIGHT*c + r, format(value, '0%db' % WIDTH), picture))
    # The comment keeps "others" out of the last glyph's group, so that the
    # "=>" of each group line up, as vsg requires.
    print('      -- The rest is blank')
    print('      others => (others => \'0\'));')
    print('')
    print('end package font_pkg;')


if __name__ == '__main__':
    main()
